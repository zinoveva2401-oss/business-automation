def suggest(text: str, limit: int = 3):
    low = text.lower()
    by_cmd = {}
    for pat, (cmd, reason, preview) in RULES:
        if re.search(pat, low, re.I):
            by_cmd.setdefault(cmd, Suggestion(cmd, reason, False, preview))

    # Generic routes should not crowd out more precise carriers.
    if '/диагностика' in by_cmd:
        by_cmd.pop('/обо-мне', None)
        by_cmd.pop('/человечески', None)
    if '/премиум-сайт' in by_cmd:
        by_cmd.pop('/сайт', None)
        by_cmd.pop('/макет', None)
    if '/обо-мне' in by_cmd or '/спасибо' in by_cmd:
        by_cmd.pop('/сайт', None)
    if '/наружка' in by_cmd:
        by_cmd.pop('/макет', None)
    if '/съёмка' in by_cmd and '/раскадровка' in by_cmd and 'снять' in low:
        # keep both only if explicit video/roll mention is present
        if not re.search(r'видео|ролик|reels|рилс|short|шортс', low):
            by_cmd.pop('/раскадровка', None)

    def rank(item):
        cmd = item.command
        try:
            return PRIORITY.index(cmd)
        except ValueError:
            return len(PRIORITY)

    found = sorted(by_cmd.values(), key=rank)[:limit]
    if len(found) == 1:
        found[0].auto_apply = True
    return found

