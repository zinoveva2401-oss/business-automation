#!/usr/bin/env python3
from pathlib import Path
import re,sys
root=Path(__file__).resolve().parents[1]
text=(root/'references/quick-command-palette.md').read_text('utf-8')
cmds=[]
for m in re.finditer(r'^- `(/[^`]+)`',text,re.M):
    c=m.group(1)
    if c not in cmds:cmds.append(c)
required=['/покажи','/майндкарта','/схема','/3d','/взрыв-схема','/разрез','/изометрия','/дашборд','/наружка','/макет','/раскадровка','/обложка','/карусель','/ролик','/съёмка','/монтаж','/книга','/продукт','/ценность','/деньги','/юрист','/портфолио','/докажи-на-себе','/сайт','/обо-мне','/спасибо','/премиум-сайт','/алгоритм','/канал','/версия-2','/речь','/образ','/научи','/модель','/дешевле','/сохрани-знание']
missing=[c for c in required if c not in cmds]

extra_required=['/диагностика','/не-придумывай','/рабочее-место','/бизнес-дашборд','/контент-панель','/карта-аудитории','/плагины','/нейросети','/парсер','/модель-экономно','/сравни-модели','/куда-не-идти','/белое-пятно']
missing += [c for c in extra_required if c not in cmds]
r5_required=['/где-клиенты','/лиды','/аутрич','/автопродажи','/воронки-варианты','/разбери-сырьё','/почисти-речь','/лучший-дубль','/обрежь-лишнее','/банк-монтажа','/что-залетает','/контент-микс','/где-мне-ai','/репетитор','/телефон-ноутбук','/системный-архитектор']
missing += [c for c in r5_required if c not in cmds]
if len(cmds)<200 or missing:
    print('НЕ ПРОЙДЕНО',len(cmds),'команд; missing',missing);sys.exit(1)
from importlib.util import spec_from_file_location,module_from_spec
sp=spec_from_file_location('q',root/'scripts/quick_command_router.py');m=module_from_spec(sp);sp.loader.exec_module(m)
cases={
'Хочу придумать лучшую версию себя, речь, одежду и работу через год':'/версия-2',
'Как должна выглядеть дорогая страница обо мне на премиальном сайте':'/обо-мне',
'После заявки хочу экран спасибо и что будет дальше':'/спасибо',
'Мы сами это применяем или только рассказываем клиентам?':'/докажи-на-себе',
'Как из нашей настройки ChatGPT сделать будущий продукт и сохранить знание':'/сохрани-знание',
'Какую модель Sol Luna Astra поставить чтобы не тратить токены':'/модель',
'Покажи объект в разобранном виде':'/взрыв-схема',
'Не хватает данных обо мне, не придумывай и сначала спроси нужное':'/диагностика',
'Хочу видеть весь контент на неделю и месяц в одной панели':'/контент-панель',
'Какие плагины нам надо поставить, чтобы закрыть текущий пробел':'/плагины',
'Luna или Sol: хочу дешевле по токенам без потери качества':'/модель-экономно',
'В этой нише слишком много конкурентов, куда нам лучше не идти':'/куда-не-идти',
'Где нам брать первых клиентов на новую услугу':'/где-клиенты',
'Хочу чтобы после настройки агент сам отвечал лидам на типовые вопросы':'/автопродажи',
'Я дала сырые видео, убери слова паразиты и лишние паузы':'/почисти-речь',
'Найди какие ролики сейчас залетают в нашей теме и предложи тест':'/что-залетает',
'Контент стал слишком продажным и скучным, хочу быть и экспертом и блогером':'/контент-микс',
'Как еще мне применять ChatGPT дома и для обучения детей':'/где-мне-ai',
'Как связать телефон и ноутбук для быстрого переноса видео':'/телефон-ноутбук',
}
for q,exp in cases.items():
    got=[x.command for x in m.suggest(q)]
    if exp not in got:
        print('НЕ ПРОЙДЕНО',q,got,'expected',exp);sys.exit(1)
print('ПРОВЕРКА ПРОЙДЕНА')
print('команд в банке:',len(cmds),'| автоподбор и расширяемый registry работают')
